// 添加/更新节假日（供运行时调用）
export function addHoliday(date: string, name: string): void {
  HOLIDAYS[date] = name
}

// 添加/更新补休日期（供运行时调用）
export function addMakeupDay(date: string, name: string): void {
  MAKEUP_DAYS[date] = name
}

// 移除节假日（供运行时调用）
export function removeHoliday(date: string): void {
  delete HOLIDAYS[date]
}

// 移除补休日期（供运行时调用）
export function removeMakeupDay(date: string): void {
  delete MAKEUP_DAYS[date]
}

// 获取所有节假日数据（供设置页面使用）
export function getAllHolidays(): Record<string, string> {
  return { ...HOLIDAYS }
}

// 获取所有补休数据（供设置页面使用）
export function getAllMakeupDays(): Record<string, string> {
  return { ...MAKEUP_DAYS }
}

// 导出数据供持久化
export function exportHolidayData(): { holidays: Record<string, string>; makeupDays: Record<string, string> } {
  return {
    holidays: { ...HOLIDAYS },
    makeupDays: { ...MAKEUP_DAYS }
  }
}

// 从持久化数据导入
export function importHolidayData(data: { holidays?: Record<string, string>; makeupDays?: Record<string, string> }): void {
  if (data.holidays) {
    Object.entries(data.holidays).forEach(([date, name]) => {
      HOLIDAYS[date] = name
    })
  }
  if (data.makeupDays) {
    Object.entries(data.makeupDays).forEach(([date, name]) => {
      MAKEUP_DAYS[date] = name
    })
  }
}